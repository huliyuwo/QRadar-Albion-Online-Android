    /** typeId 在表中的下标；不是活体资源返回 -1（二分查找）。 */
    public static int indexOf(int typeId)
    {
        int low = 0;
        int high = TYPE_IDS.length - 1;

        while (low <= high)
        {
            int mid = (low + high) >>> 1;
            int value = TYPE_IDS[mid];

            if (value < typeId)
            {
                low = mid + 1;
            }
            else if (value > typeId)
            {
                high = mid - 1;
            }
            else
            {
                return mid;
            }
        }

        return -1;
    }

    /** 是否是活体资源（loot 为 HIDE/FIBER/WOOD/ROCK/ORE 的怪）。 */
    public static boolean isLivingResource(int typeId)
    {
        return indexOf(typeId) >= 0;
    }

    /** 资源类别名（fiber/hide/logs/rock/ore），非活体资源返回 null。 */
    public static String kindOf(int typeId)
    {
        int index = indexOf(typeId);
        return index < 0 ? null : KIND_NAMES[KINDS[index]];
    }

    /** 资源类别编码（KIND_*），非活体资源返回 -1。 */
    public static int kindCodeOf(int typeId)
    {
        int index = indexOf(typeId);
        return index < 0 ? -1 : KINDS[index];
    }

    /** 资源 tier（1..8），非活体资源返回 0。 */
    public static int tierOf(int typeId)
    {
        int index = indexOf(typeId);
        return index < 0 ? 0 : TIERS[index];
    }

    /** 是否为可剥皮（hide）类活体资源。 */
    public static boolean isSkinnable(int typeId)
    {
        int index = indexOf(typeId);
        return index >= 0 && KINDS[index] == KIND_HIDE;
    }

    /** 表内条目数。 */
    public static int size()
    {
        return TYPE_IDS.length;
    }
